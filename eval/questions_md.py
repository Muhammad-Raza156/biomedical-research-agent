"""Render QUESTIONS.md from an eval results file (answers and claims fetched through the public API).

Usage: python eval/questions_md.py eval/results/<run>.json [--stream <tier3 question id>] > QUESTIONS.md
Needs env GRAPH_READER_PASSWORD (gold answers are re-run as the read-only user).
"""

from __future__ import annotations

import argparse
import json
import os
import re
from pathlib import Path

import httpx
import yaml
from neo4j import GraphDatabase

HERE = Path(__file__).parent
TIER_TITLES = {"1": "Tier 1 — single hop", "2": "Tier 2 — multi-hop", "3": "Tier 3 — temporal / path / comparison",
               "adversarial": "Adversarial set"}


def redact(text: str) -> str:
    """Provider error messages name the account's organization; keep that out of a public file."""
    return re.sub(r"org_[0-9A-Za-z]+", "org_[redacted]", text)


def gold_answers(driver, cypher: str) -> list[str]:
    records, _, _ = driver.execute_query(cypher, database_="neo4j")
    return sorted({str(r["answer"]) for r in records if r["answer"] is not None})


def stream_events(api: httpx.Client, query_id: str) -> list[dict]:
    events = []
    with api.stream("GET", f"/queries/{query_id}/stream", timeout=60) as response:
        for line in response.iter_lines():
            if line.startswith("data: "):
                events.append(json.loads(line[6:]))
    return events


def render_question(item: dict, row: dict, status: dict, gold: list[str] | None) -> list[str]:
    out = [f"### `{item['id']}`", "", f"**Question:** {item['question']}", ""]
    if row.get("model"):
        out += [f"**Model:** `{row['model']}`", ""]
    if item["tier"] == "adversarial":
        out += [(f"**Type:** {item['kind']} · **Result:** {'PASS' if row.get('passed') else 'FAIL'} "
                f"(status `{row['status']}`)"), ""]
    else:
        out += [(f"**Scores:** precision {row.get('precision')} · recall {row.get('recall')} · "
                f"citation validity {row.get('citation_validity')} (status `{row['status']}`)"), ""]
    answer = status.get("answer") or {}
    if status.get("status") == "awaiting_input" or row["status"] == "awaiting_input":
        out += ["**Agent:** asked for clarification (the run was then cancelled by the harness).", ""]
    elif answer:
        out += ["**Answer:**", "", *[f"> {line}" for line in answer["answer"].splitlines()], ""]
        if answer.get("claims"):
            out += ["<details><summary>Verified claims, PMIDs and the Cypher behind each</summary>", ""]
            for i, claim in enumerate(answer["claims"], 1):
                out += [f"{i}. {claim['text']} — PMIDs {', '.join(claim['pmids'])}"
                        + (f" — ⚠ {'; '.join(claim['warnings'])}" if claim.get("warnings") else ""),
                        "", "   ```cypher", *[f"   {line}" for line in claim["cypher"].splitlines()], "   ```", ""]
            out += ["</details>", ""]
        out += [(f"Claims checked/passed/dropped: {answer['claims_checked']}/{answer['claims_passed']}/"
                f"{answer['claims_dropped']} · tokens {answer['total_tokens']}"), ""]
    elif status.get("error"):
        out += [f"**Error:** {redact(status['error'][:300])}", ""]
    if gold is not None:
        shown = ", ".join(gold[:25]) + (f" … (+{len(gold) - 25} more)" if len(gold) > 25 else "")
        out += ["<details><summary>Gold Cypher and gold answer</summary>", "", "```cypher",
                item["gold_cypher"].rstrip(), "```", "", f"Gold ({len(gold)}): {shown}", "", "</details>", ""]
    return out


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("results")
    parser.add_argument("--api", default="http://localhost:8000")
    parser.add_argument("--stream", help="question id whose full thinking stream is included")
    args = parser.parse_args()
    items = {i["id"]: i for i in yaml.safe_load((HERE / "questions.yaml").read_text(encoding="utf-8"))}
    rows = json.loads(Path(args.results).read_text(encoding="utf-8"))

    lines = ["# Questions, answers and claims", "",
             ("Generated by `eval/questions_md.py` from the evaluation run; scores and analysis are in "
             "[EVAL.md](EVAL.md). Tier 4 was not attempted."), ""]
    with GraphDatabase.driver("bolt://localhost:7687",
                              auth=("agent_reader", os.environ["GRAPH_READER_PASSWORD"])) as driver, \
            httpx.Client(base_url=args.api, timeout=60) as api:
        for tier, title in TIER_TITLES.items():
            tier_rows = [r for r in rows if str(r["tier"]) == tier]
            if not tier_rows:
                continue
            lines += [f"## {title}", ""]
            for row in tier_rows:
                item = items[row["id"]]
                status = api.get(f"/queries/{row['query_id']}").json()
                gold = gold_answers(driver, item["gold_cypher"]) if "gold_cypher" in item else None
                lines += render_question(item, row, status, gold)
        if args.stream:
            row = next(r for r in rows if r["id"] == args.stream)
            lines += [f"## Full thinking stream — `{args.stream}`", "",
                      f"Replayed with `curl -N {args.api}/queries/{row['query_id']}/stream` after the run finished.",
                      "", "<details><summary>Thinking stream</summary>", "",
                      "| step | node | type | content |", "|---|---|---|---|"]
            for e in stream_events(api, row["query_id"]):
                content = e["content"].replace("|", "\\|").replace("\n", " ")
                if e["type"] == "graph_query":
                    content = json.loads(e["meta"]).get("cypher", "").replace("|", "\\|").replace("\n", " ")
                lines.append(f"| {e['step']} | {e['node']} | {e['type']} | {content[:300]} |")
            lines += ["", "</details>", ""]
    print("\n".join(lines))


if __name__ == "__main__":
    main()
